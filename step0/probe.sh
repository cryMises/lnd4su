#!/bin/bash
# step0/probe.sh - Step-0 sandbox probe for lnd4su.
#
# Goal: prove ioi/isolate works inside a privileged container on ARM64 Ubuntu
# with cgroup v2, and that all six verdicts are produced with per-test time
# and memory reported.
#
# Run (preferred):
#   docker run --rm --privileged --cgroupns=host \
#     -v /sys/fs/cgroup:/sys/fs/cgroup:rw lnd4su-step0
#
# Notes:
#   * --privileged is required: isolate mounts a box chroot and creates
#     cgroups; both need CAP_SYS_ADMIN.
#   * host must be cgroup v2: stat -fc %T /sys/fs/cgroup -> cgroup2fs
#   * isolate --mem / --cg-mem are in KB, so 65536 means 64 MB.
#   * no set -e: every case must run even when a previous one failed.
set -u

BOX_ID=${LND4SU_STEP0_BOX_ID:-0}
BOX_ROOT=/var/local/isolate
BOX="$BOX_ROOT/$BOX_ID/box"
PASSES=0
FAILS=0
META_MARK=/tmp/step0-meta-dumped

say() { printf '%s\n' "$*"; }

ok()   { printf 'RESULT %-3s PASS  time=%ss mem=%sKB\n' "$1" "$2" "$3"; }
fail() { printf 'RESULT %-3s FAIL  time=%ss mem=%sKB\n' "$1" "$2" "$3"
         printf '%s FAIL: %s\n' "$1" "$4" >&2; }

# first value of key <k> in an isolate meta file
meta() { awk -F: -v k="$2" '$1==k {print $2; exit}' "$1" 2>/dev/null; }

# --- must be root: isolate's setuid sandbox needs it ------------------------
if [ "$(id -u)" != 0 ]; then
    say "FATAL: must run as root (isolate sandbox)"
    exit 1
fi

# --- environment report -----------------------------------------------------
say "== lnd4su step0 probe =="
say "cgroup version: $(stat -fc %T /sys/fs/cgroup 2>/dev/null || echo unknown)"
say "container privileged check: $(grep CapEff /proc/self/status 2>/dev/null || echo unknown)"
say "isolate: $(isolate --version 2>&1 | head -n 1)"

CONTROLLERS=""
[ -r /sys/fs/cgroup/cgroup.controllers ] && CONTROLLERS=$(cat /sys/fs/cgroup/cgroup.controllers)
say "cgroup controllers: ${CONTROLLERS:-none}"
case " $CONTROLLERS " in
    *" memory "*) ;;
    *) say "WARN: memory controller missing from cgroup.controllers; MLE may not work" ;;
esac

# --- isolate config ---------------------------------------------------------
# The isolate package normally ships isolate-setup.sh and systemd units which
# create these paths and run `isolate --check-config`. When they are present,
# trust --check-config output over this manual fallback.
mkdir -p /usr/local/etc
cat > /usr/local/etc/isolate <<'EOF'
# generated by the lnd4su step0 probe
box_root = /var/local/isolate
lock_root = /run/isolate/locks
cg_root = auto:/run/isolate/cgroup
first_uid = 60000
first_gid = 60000
num_boxes = 100
EOF
say "wrote config /usr/local/etc/isolate"
mkdir -p /run/isolate/locks "$BOX_ROOT"

if [ -n "${LND4SU_CGROUP_ROOT:-}" ]; then
    CG_PATH=$LND4SU_CGROUP_ROOT
else
    CG_PATH=/sys/fs/cgroup/lnd4su
fi
say "cgroup path: $CG_PATH"
if [ ! -w /sys/fs/cgroup ]; then
    say "ERROR: /sys/fs/cgroup is not writable; the container needs --privileged with it mounted rw"
fi
# isolate writes <parent>/box-<id>/memory.max, so <parent> must have the memory
# controller enabled for its children. cgroup v2 refuses that on a cgroup that
# still holds processes, and this container's cgroup always holds PID 1 — so use
# a fresh empty pool under the cgroup mount instead. The root is exempt from the
# no-internal-process rule and the pool starts with no processes at all.
mkdir -p "$CG_PATH"
enable_mem() {
    local p="$1"
    grep -qw memory "$p/cgroup.subtree_control" 2>/dev/null && return 0
    if ! echo "+memory" > "$p/cgroup.subtree_control" 2>/dev/null; then
        say "ERROR: cannot enable memory on $p/cgroup.subtree_control"
        return 1
    fi
}
enable_mem /sys/fs/cgroup || true
enable_mem "$CG_PATH" || true
printf '%s\n' "$CG_PATH" > /run/isolate/cgroup
say "cgroup path file /run/isolate/cgroup -> $CG_PATH"
say "memory.max under pool: $(cat "$CG_PATH/memory.max" 2>/dev/null || echo MISSING)"

# --- one case through isolate ----------------------------------------------
# $1 = expected verdict (AC|WA|TLE|MLE|RE|CE), $2 = file in /probe/cases
# Body is a subshell so the trap cleanup and cd never leak into the next case.
run_case() (
    local v="$1" src="$2"
    local rc box t mem status oom killed out cm
    local BOX="$BOX_ROOT/$BOX_ID/box"

    cd /probe || exit 1

    cleanup_box() {
        cd /probe 2>/dev/null
        isolate --cg --box-id="$BOX_ID" --silent --cleanup >/dev/null 2>&1
        rm -rf "$BOX_ROOT/$BOX_ID"
    }
    trap cleanup_box EXIT

    # stale box from an earlier run would poison the result
    isolate --cg --box-id="$BOX_ID" --silent --cleanup >/dev/null 2>&1
    rm -rf "$BOX_ROOT/$BOX_ID"

    box=$(isolate --cg --box-id="$BOX_ID" --silent --init 2>/dev/null | tail -n 1)
    case "$box" in
        /*) ;;
        *) box="" ;;
    esac
    [ -n "$box" ] && [ -d "$box" ] || box="$BOX"
    if [ ! -d "$box" ]; then
        fail "$v" - - "isolate --init produced no box dir"
        exit 1
    fi

    cp "/probe/cases/$src" "$box/main.c" || {
        fail "$v" - - "cannot copy cases/$src into box"
        exit 1
    }
    # the sandbox user (uid 60000) must be able to write prog into its own /box
    chmod 0777 "$box"

    cd "$box" || { fail "$v" - - "cannot enter box dir"; exit 1; }

    # One-shot self-test with NO redirection at all: everything the sandbox
    # prints lands on this console, and isolate's own complaints are kept too.
    # This must name the cause in a single run -- no more guessing.
    if [ ! -f /tmp/step0-diag-dumped ]; then
        say "--- self-test 1: does /bin/sh run in the box? ---"
        isolate --cg --box-id="$BOX_ID" \
            --time=10 --wall-time=20 --mem=1048576 --processes=64 \
            --env=PATH=/usr/local/bin:/usr/bin:/bin \
            --run -- /bin/sh -c 'echo SANDBOX-ALIVE; id; pwd; echo PATH=$PATH; ls -l /box; echo REDIRECT-OK > /box/redir.txt; echo WROTE' 2>&1
        say "self-test 1 rc=$?"
        say "redir.txt content: $(cat "$box/redir.txt" 2>&1)"
        say "--- isolate check-config ---"
        isolate --check-config 2>&1 | head -20
        say "--- end check-config ---"

        # real source is already in /box/main.c; compile it with no redirection
        say "--- self-test 2: bare gcc, output straight to console ---"
        isolate --cg --box-id="$BOX_ID" \
            --time=10 --wall-time=20 --mem=1048576 --processes=64 --fsize=16384 \
            --env=PATH=/usr/local/bin:/usr/bin:/bin \
            --meta="$BOX_ROOT/$BOX_ID/smoke.meta" \
            --run -- /usr/bin/gcc -O2 -std=c17 -o prog main.c 2>&1
        say "self-test 2 rc=$?"
        say "--- self-test 2 meta ---"
        cat "$BOX_ROOT/$BOX_ID/smoke.meta" 2>/dev/null
        say "--- host view of $box ---"
        ls -la "$box" 2>/dev/null
        say "--- which gcc on the host ---"
        ls -l /usr/bin/gcc /usr/bin/cc1 2>&1
        command -v gcc cc1 2>&1
        say "--- end self-test ---"
        : > /tmp/step0-diag-dumped
    fi

    # compile INSIDE the sandbox; the CE case must fail right here
    # --meta is opened by isolate on the host (before the chroot), so it needs
    # an absolute path; --stderr is opened inside the box.
    # isolate starts the program with an almost empty environment, so gcc needs
    # PATH to find cc1/as/ld.
    isolate --cg --box-id="$BOX_ID" --silent \
        --time=10 --wall-time=20 --mem=1048576 --processes=64 --fsize=16384 \
        --env=PATH=/usr/local/bin:/usr/bin:/bin \
        --meta="$BOX_ROOT/$BOX_ID/compile.meta" --stderr=compile.err --run -- \
        /usr/bin/gcc -O2 -std=c17 -o prog main.c
    rc=$?
    status=$(meta "$BOX_ROOT/$BOX_ID/compile.meta" status)

    if [ "$v" = CE ]; then
        if [ "$rc" -ne 0 ] || { [ -n "$status" ] && [ "$status" != OK ]; }; then
            printf 'RESULT %-3s PASS  (compile rejected)\n' CE
            exit 0
        fi
        printf 'RESULT %-3s FAIL  (compile rejected)\n' CE
        printf 'CE FAIL: broken source compiled cleanly (status=%s)\n' "${status:-none}" >&2
        exit 1
    fi

    if [ "$rc" -ne 0 ] || [ "$status" != OK ]; then
        say "--- compile meta ---"
        cat "$BOX_ROOT/$BOX_ID/compile.meta" 2>/dev/null
        say "--- compile.err ---"
        head -c 2000 compile.err 2>/dev/null
        say "--- end compile.err ---"
        fail "$v" - - "compile failed (status=${status:-none} rc=$rc)"
        exit 1
    fi

    # run: 1s CPU, 4s wall, 64 MB cgroup memory cap, 2 MB output cap.
    # --mem is the address-space backstop; keeping it above --cg-mem is what
    # lets the OOM killer fire instead of malloc failing (which would be RE).
    printf '2 3\n' > input.txt
    isolate --cg --box-id="$BOX_ID" --silent \
        --time=1 --wall-time=4 --mem=131072 --cg-mem=65536 --fsize=2048 \
        --meta="$BOX_ROOT/$BOX_ID/run.meta" --stdin=input.txt \
        --stdout=output.txt --stderr=run.err \
        --run -- /box/prog
    rc=$?

    t=$(meta "$BOX_ROOT/$BOX_ID/run.meta" time)
    [ -n "$t" ] || t="-"
    mem=$(meta "$BOX_ROOT/$BOX_ID/run.meta" cg-mem)
    [ -n "$mem" ] || mem=$(meta "$BOX_ROOT/$BOX_ID/run.meta" max-rss)
    [ -n "$mem" ] || mem="-"
    status=$(meta "$BOX_ROOT/$BOX_ID/run.meta" status)
    oom=$(meta "$BOX_ROOT/$BOX_ID/run.meta" cg-oom-killed)
    killed=$(meta "$BOX_ROOT/$BOX_ID/run.meta" killed)
    cm=$(meta "$BOX_ROOT/$BOX_ID/run.meta" cg-mem)

    # raw meta once, so the operator can verify memory reporting is real
    if [ ! -f "$META_MARK" ]; then
        say "--- raw run.meta ($v) ---"
        cat "$BOX_ROOT/$BOX_ID/run.meta" 2>/dev/null
        say "--- end run.meta ---"
        : > "$META_MARK"
    fi

    case "$v" in
        AC|WA)
            out=$(tr -d '[:space:]' < output.txt 2>/dev/null)
            if [ "$rc" -eq 0 ] && [ "$status" = OK ]; then
                if [ "$v" = AC ]; then
                    if [ "$out" = 5 ]; then ok AC "$t" "$mem"; exit 0; fi
                    fail AC "$t" "$mem" "expected output 5, got '${out}'"
                    exit 1
                fi
                if [ "$out" != 5 ]; then ok WA "$t" "$mem"; exit 0; fi
                fail WA "$t" "$mem" "got correct output 5, WA not produced"
                exit 1
            fi
            fail "$v" "$t" "$mem" "expected OK, got status=${status:-none} rc=$rc"
            exit 1
            ;;
        TLE)
            if [ "$status" = TO ] || { [ "$status" = SG ] && [ -n "$killed" ]; }; then
                ok TLE "$t" "$mem"
                exit 0
            fi
            fail TLE "$t" "$mem" "expected TO, got status=${status:-none} rc=$rc"
            exit 1
            ;;
        MLE)
            if [ -n "$oom" ] || awk -v m="$cm" 'BEGIN{exit !(m+0 >= 60000)}'; then
                ok MLE "$t" "$mem"
                say "MLE cg-mem=${cm:-?}KB (limit 65536KB) cg-oom-killed=${oom:-0}"
                exit 0
            fi
            fail MLE "$t" "$mem" "expected cgroup OOM kill, got status=${status:-none} cg-mem=${cm:-none}"
            exit 1
            ;;
        RE)
            case "$status" in
                SG|RE) ok RE "$t" "$mem"; exit 0 ;;
            esac
            fail RE "$t" "$mem" "expected SG/RE, got status=${status:-none} rc=$rc"
            exit 1
            ;;
    esac

    fail "$v" - - "unclassified case"
    exit 1
)

# EXPECTED: AC  - reads "2 3", prints 5
# EXPECTED: WA  - reads "2 3", prints 6 (wrong answer, must be detected)
# EXPECTED: TLE - infinite loop, killed by the CPU/wall limit
# EXPECTED: MLE - allocates and touches pages until the 64 MB cgroup cap kills it
# EXPECTED: RE  - null pointer write, dies by signal
# EXPECTED: CE  - syntax error, rejected at compile time
for spec in "AC ac.c" "WA wa.c" "TLE tle.c" "MLE mle.c" "RE re.c" "CE ce_broken.c"; do
    if run_case $spec; then
        PASSES=$((PASSES + 1))
    else
        FAILS=$((FAILS + 1))
    fi
done

say "SUMMARY pass=$PASSES/6"
[ "$FAILS" -eq 0 ] || exit 1
exit 0
