#!/bin/bash
# step0b/probe0b.sh - Step-0b: does a SECOND worker fit?
#
# Question: the box has ~200 MB headroom. One gcc compile can spike to ~300 MB
# for a second or two. The spec asks for 2 workers "if it fits" and requires a
# MEASUREMENT, not a guess. This runs two full submission pipelines concurrently
# (two compiles + two runs, each with the app's real limits) and reports whether
# the peak stayed inside headroom.
#
# Swap growth is the decisive signal on this box: it already sits near its swap
# ceiling, so growth under judging means the second worker pressures the nine
# services that are already running. Override with LND4SU_SWAP_GROWTH_MB.
#
# Run (same privileged shape as Step 0):
#   docker run --rm --privileged --cgroupns=host \
#     -v /sys/fs/cgroup:/sys/fs/cgroup:rw lnd4su-step0b
#
# Output ends with a VERDICT line: KEEP 2 WORKERS or SHIP 1 WORKER, plus the
# measured numbers. The script does NOT decide by itself what "headroom" means
# for the host -- it prints the numbers the user judges (spec: borderline
# measurements are reported, never guessed).
set -u

BOX_ROOT=/var/local/isolate
CG_MOUNT=/sys/fs/cgroup
MAX_MB=${LND4SU_MEM_HEADROOM_MB:-200}   # spec: 200 MB headroom for the judge

say() { printf '%s\n' "$*"; }
meta() { awk -F: -v k="$2" '$1==k {print $2; exit}' "$1" 2>/dev/null; }

# Memory in use, in MB, for two cgroups:
#   host  - <mount>/memory.current. With --cgroupns=host plus a bind-mounted
#           /sys/fs/cgroup this is the HOST root, so it counts music-vm's other
#           nine services too. That is the number the gate cares about: how much
#           extra does judging add on top of everything already running.
#   pool  - the judge's own cgroup pool, i.e. just the sandboxed work.
# memory.peak is deliberately not used: it is cumulative since boot, so any
# earlier run would poison the baseline.
# An unreadable or unparsable file yields "NA", never 0: a silent zero would
# look like a real measurement and turn the gate into a rubber stamp.
mb_of() {
    local v
    [ -r "$1" ] || { echo NA; return; }
    v=$(cat "$1" 2>/dev/null)
    case "$v" in ''|max) echo NA; return ;; esac
    case "$v" in *[!0-9]*) echo NA; return ;; esac
    echo $(( v / 1024 / 1024 ))
}
host_mb() { mb_of "$CG_MOUNT/memory.current"; }
pool_mb() { mb_of "$CG_PATH/memory.current"; }

# MemAvailable is host-wide inside the container (it reads the host /proc), so
# it works even when a cgroup file is not readable. It is also the honest
# question for a shared box: how much memory the other services LOST while
# judging ran. Kept as a second, independent signal.
avail_mb() { awk '/^MemAvailable:/ {print int($2/1024); exit}' /proc/meminfo; }

if [ "$(id -u)" != 0 ]; then
    say "FATAL: must run as root (isolate sandbox)"
    exit 1
fi

say "== lnd4su step0b probe: 2-worker capacity =="
say "cgroup version: $(stat -fc %T "$CG_MOUNT" 2>/dev/null || echo unknown)"
say "isolate: $(isolate --version 2>&1 | head -n 1)"

mkdir -p /usr/local/etc /run/isolate/locks "$BOX_ROOT"
cat > /usr/local/etc/isolate <<'EOF'
# generated by the lnd4su step0b probe
box_root = /var/local/isolate
lock_root = /run/isolate/locks
cg_root = auto:/run/isolate/cgroup
first_uid = 60000
first_gid = 60000
num_boxes = 100
EOF

CG_PATH=${LND4SU_CGROUP_ROOT:-$CG_MOUNT/lnd4su}
mkdir -p "$CG_PATH"
enable_mem() {
    local p="$1"
    grep -qw memory "$p/cgroup.subtree_control" 2>/dev/null && return 0
    echo "+memory" > "$p/cgroup.subtree_control" 2>/dev/null && return 0
    say "ERROR: cannot enable memory on $p/cgroup.subtree_control"
    return 1
}
enable_mem "$CG_MOUNT" || true
enable_mem "$CG_PATH" || true
printf '%s\n' "$CG_PATH" > /run/isolate/cgroup
say "cgroup pool: $CG_PATH (memory.max=$(cat "$CG_PATH/memory.max" 2>/dev/null || echo MISSING))"

swap_mb() { awk '/^SwapTotal:/ {t=$2} /^SwapFree:/ {f=$2} END {print int((t-f)/1024)}' /proc/meminfo; }

BEFORE_HOST=$(host_mb)
BEFORE_SWAP=$(swap_mb)
BEFORE_POOL=$(pool_mb)
BEFORE_AVAIL=$(avail_mb)
say "host memory.current before: ${BEFORE_HOST} MB (whole box)"
say "pool memory.current before: ${BEFORE_POOL} MB (judge only)"
say "MemAvailable before: ${BEFORE_AVAIL} MB"
say "swap in use before: ${BEFORE_SWAP} MB"
say "probe reads: /sys/fs/cgroup/memory.current=$( [ -r "$CG_MOUNT/memory.current" ] && echo readable || echo UNREADABLE) ${CG_PATH}/memory.current=$( [ -r "$CG_PATH/memory.current" ] && echo readable || echo UNREADABLE)"

# One full pipeline: init -> compile a real C++ submission -> run it on 3 cases.
# $1 = box id. Mirrors the app: compile 10 s / 512 MB, cases 1 s / 64 MB.
pipeline() (
    local bid="$1"
    local box boxd
    cleanup_box() {
        cd /probe 2>/dev/null
        isolate --cg --box-id="$bid" --silent --cleanup >/dev/null 2>&1
        rm -rf "$BOX_ROOT/$bid"
    }
    trap cleanup_box EXIT

    isolate --cg --box-id="$bid" --silent --cleanup >/dev/null 2>&1
    rm -rf "$BOX_ROOT/$bid"

    box=$(isolate --cg --box-id="$bid" --silent --init 2>/dev/null | tail -n 1)
    [ -n "$box" ] && [ -d "$box" ] || box="$BOX_ROOT/$bid"
    boxd="$box/box"
    mkdir -p "$boxd"
    cp /probe/cases/heavy.cpp "$boxd/main.cpp" || { say "worker $bid: no source"; exit 1; }
    chmod 0777 "$boxd"
    cd "$boxd" || exit 1

    isolate --cg --box-id="$bid" --silent \
        --time=10 --wall-time=20 --mem=1048576 --cg-mem=524288 \
        --processes=64 --fsize=16384 --env=PATH=/usr/local/bin:/usr/bin:/bin \
        --meta="$BOX_ROOT/$bid/c.meta" --stderr=compile.err --run -- \
        /usr/bin/g++ -O2 -std=c++17 -o prog main.cpp
    local st
    st=$(meta "$BOX_ROOT/$bid/c.meta" status)
    [ -n "$st" ] || st=OK
    if [ "$st" != OK ]; then
        say "worker $bid: COMPILE FAILED status=$st"
        head -c 800 compile.err 2>/dev/null
        exit 1
    fi
    say "worker $bid: compiled ($(meta "$BOX_ROOT/$bid/c.meta" time)s, $(meta "$BOX_ROOT/$bid/c.meta" cg-mem)KB)"

    local i peak=0 m
    for i in 1 2 3; do
        printf '2 3\n' > input.txt
        isolate --cg --box-id="$bid" --silent \
            --time=1 --wall-time=4 --mem=131072 --cg-mem=65536 --fsize=1024 \
            --meta="$BOX_ROOT/$bid/r.meta" --stdin=input.txt \
            --stdout=output.txt --stderr=run.err --run -- /box/prog
        m=$(meta "$BOX_ROOT/$bid/r.meta" cg-mem)
        [ -n "$m" ] || m=0
        [ "$m" -gt "$peak" ] && peak=$m
    done
    say "worker $bid: 3 cases done, peak cg-mem ${peak}KB"
)

# --- the measurement: two pipelines at once, sampled throughout -------------
SAMPLES=/tmp/step0b.samples
: > "$SAMPLES"
(
    while :; do
        printf '%s %s %s\n' "$(host_mb)" "$(pool_mb)" "$(avail_mb)" >> "$SAMPLES"
        sleep 0.2
    done
) &
SAMPLER=$!

START=$(date +%s%N)
pipeline 0 > /tmp/w0.log 2>&1 &
W0=$!
sleep 0.15                       # let worker 0 get into its compile first
pipeline 1 > /tmp/w1.log 2>&1 &
W1=$!
wait $W0; R0=$?
wait $W1; R1=$?
END=$(date +%s%N)
kill $SAMPLER 2>/dev/null
wait $SAMPLER 2>/dev/null

cat /tmp/w0.log /tmp/w1.log

PEAK_HOST=$(awk '$1 ~ /^[0-9]+$/ {if ($1+0 > m) m=$1+0} END {print (NR && m != "" ? m : "NA")}' "$SAMPLES" 2>/dev/null)
PEAK_POOL=$(awk '$2 ~ /^[0-9]+$/ {if ($2+0 > m) m=$2+0} END {print (NR && m != "" ? m : "NA")}' "$SAMPLES" 2>/dev/null)
MIN_AVAIL=$(awk '$3 ~ /^[0-9]+$/ {if (m == "" || $3+0 < m) m=$3+0} END {print (NR && m != "" ? m : "NA")}' "$SAMPLES" 2>/dev/null)
[ -n "${PEAK_HOST:-}" ] || PEAK_HOST=NA
[ -n "${PEAK_POOL:-}" ] || PEAK_POOL=NA
[ -n "${MIN_AVAIL:-}" ] || MIN_AVAIL=NA
DUR=$(( (END - START) / 1000000 ))

say "--- measurement ---"
say "wall time for both pipelines: ${DUR} ms"
say "peak host memory.current: ${PEAK_HOST} MB (baseline ${BEFORE_HOST} MB)"
say "peak pool memory.current: ${PEAK_POOL} MB (judging alone)"
say "lowest MemAvailable: ${MIN_AVAIL} MB (baseline ${BEFORE_AVAIL} MB)"
say "headroom budget: ${MAX_MB} MB"
say "worker exit codes: $R0 $R1"

if [ "$R0" -ne 0 ] || [ "$R1" -ne 0 ]; then
    say "VERDICT: INCONCLUSIVE -- a pipeline failed, fix that before judging capacity"
    exit 1
fi


AFTER_SWAP=$(swap_mb)
SWAP_GROWTH=$(( AFTER_SWAP - BEFORE_SWAP ))
say "swap in use after: ${AFTER_SWAP} MB (growth ${SWAP_GROWTH} MB)"

# Swap growth is decisive: this box already sits near its swap ceiling, so any
# growth under judging means the second worker pushes real pressure onto the
# nine services that are already there. The MB budget is the second test.
SWAP_LIMIT=${LND4SU_SWAP_GROWTH_MB:-8}

# Two independent memory signals, either one is usable:
#   DELTA      - peak host memory.current over baseline (cgroup, exact)
#   AVAIL_DROP - how much MemAvailable the box lost (fallback, always readable)
DELTA=NA
if [ "$PEAK_HOST" != NA ] && [ "$BEFORE_HOST" != NA ]; then
    DELTA=$(( PEAK_HOST - BEFORE_HOST ))
    [ "$DELTA" -lt 0 ] && DELTA=0
fi
AVAIL_DROP=NA
if [ "$MIN_AVAIL" != NA ] && [ "$BEFORE_AVAIL" != NA ]; then
    AVAIL_DROP=$(( BEFORE_AVAIL - MIN_AVAIL ))
    [ "$AVAIL_DROP" -lt 0 ] && AVAIL_DROP=0
fi

say "memory delta: ${DELTA} MB (cgroup), avail drop: ${AVAIL_DROP} MB"

if [ "$DELTA" = NA ] && [ "$AVAIL_DROP" = NA ]; then
    say "VERDICT: INCONCLUSIVE -- neither memory signal was readable."
    say "Swap grew ${SWAP_GROWTH} MB (limit ${SWAP_LIMIT} MB). Report these numbers."
    exit 1
fi

if [ "$SWAP_GROWTH" -gt "$SWAP_LIMIT" ]; then
    say "VERDICT: SHIP 1 WORKER -- swap grew ${SWAP_GROWTH} MB (limit ${SWAP_LIMIT} MB); judging pushed the box into swap"
    exit 0
fi

# Whichever signals are readable must clear the headroom budget. Both are
# checked: on a box that already runs nine other services, a disagreement
# between them is not something to average away -- if either says the box
# suffered, the second worker does not ship.
OVER=""
[ "$DELTA" != NA ] && [ "$DELTA" -gt "$MAX_MB" ] && OVER="cgroup memory grew ${DELTA} MB"
[ "$AVAIL_DROP" != NA ] && [ "$AVAIL_DROP" -gt "$MAX_MB" ] && OVER="${OVER:+$OVER; }the box lost ${AVAIL_DROP} MB of MemAvailable"

if [ -n "$OVER" ]; then
    say "VERDICT: SHIP 1 WORKER -- over the ${MAX_MB} MB headroom: ${OVER}"
else
    say "VERDICT: KEEP 2 WORKERS -- cgroup delta ${DELTA} MB, MemAvailable drop ${AVAIL_DROP} MB, swap growth ${SWAP_GROWTH} MB, all inside budget"
fi
exit 0
